// English uses en-GB: day before month, 24-hour clock, like the other languages.
const LOCALE_MAP = { en: 'en-GB', pt: 'pt-PT', es: 'es-ES', de: 'de-DE', it: 'it-IT', fr: 'fr-FR' };

let lang = localStorage.getItem('solastat_lang') || 'en';

function t(key, vars) {
  let s = (I18N[lang] && I18N[lang][key]) || I18N.en[key] || key;
  if (vars) for (const k in vars) s = s.split('{' + k + '}').join(vars[k]);
  return s;
}

function locale() {
  return LOCALE_MAP[lang] || 'en-GB';
}

// Dates are always shown day first — DD/MM/YYYY, times on a 24-hour clock —
// whatever the language, never month first.
function pad2(n) { return String(n).padStart(2, '0'); }
function fmtDate(d) {
  return pad2(d.getDate()) + '/' + pad2(d.getMonth() + 1) + '/' + d.getFullYear();
}
function fmtDateTime(d, withSeconds) {
  const time = pad2(d.getHours()) + ':' + pad2(d.getMinutes()) + (withSeconds ? ':' + pad2(d.getSeconds()) : '');
  return fmtDate(d) + ' ' + time;
}
// isoDateToDisplay turns "YYYY-MM-DD" into "DD/MM/YYYY" and "YYYY-MM" into "MM/YYYY".
function isoDateToDisplay(iso) {
  const p = String(iso || '').split('-');
  if (p.length === 3) return p[2] + '/' + p[1] + '/' + p[0];
  if (p.length === 2) return p[1] + '/' + p[0];
  return iso || '';
}
// displayToIsoDate parses "DD/MM/YYYY" into "YYYY-MM-DD", or '' if it isn't a real date.
function displayToIsoDate(s) {
  const m = /^\s*(\d{1,2})\/(\d{1,2})\/(\d{4})\s*$/.exec(s || '');
  if (!m) return '';
  const day = +m[1], month = +m[2], year = +m[3];
  const d = new Date(year, month - 1, day);
  if (d.getFullYear() !== year || d.getMonth() !== month - 1 || d.getDate() !== day) return '';
  return year + '-' + pad2(month) + '-' + pad2(day);
}

// Links to solastat.com open in the app's language (the site reads ?lang=).
// Elements with data-site-href="page.html" get their href from here and
// follow language changes through applyStaticI18n().
const SITE_URL = 'https://www.solastat.com/';
function siteUrl(path) {
  return SITE_URL + (path || '') + '?lang=' + encodeURIComponent(lang);
}

// Applies the current language to every element on the page declaring one
// of the three data-i18n* attributes a page might use:
//  - data-i18n              -> textContent
//  - data-i18n-placeholder  -> placeholder attribute
//  - data-i18n-aria-label   -> aria-label attribute
function applyStaticI18n() {
  document.documentElement.lang = lang;
  document.querySelectorAll('[data-i18n]').forEach((el) => { el.textContent = t(el.dataset.i18n); });
  document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => { el.setAttribute('placeholder', t(el.dataset.i18nPlaceholder)); });
  document.querySelectorAll('[data-i18n-aria-label]').forEach((el) => { el.setAttribute('aria-label', t(el.dataset.i18nAriaLabel)); });
  document.querySelectorAll('[data-i18n-title]').forEach((el) => { el.setAttribute('title', t(el.dataset.i18nTitle)); });
  document.querySelectorAll('[data-site-href]').forEach((el) => { el.href = siteUrl(el.dataset.siteHref); });
}

// Switches the active language, persists it, and reapplies static markup.
// Callers that need to also refresh dynamically-generated text (e.g. the
// dashboard's live chart/status values) should do that themselves right
// after calling this — see each page's own lang-select handler.
function setLang(newLang) {
  lang = newLang;
  try { localStorage.setItem('solastat_lang', newLang); } catch (_) {}
  applyStaticI18n();
}
